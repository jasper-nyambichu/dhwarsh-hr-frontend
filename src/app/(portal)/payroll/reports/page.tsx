import { requirePermission } from "@/app/lib/dal";
import { BarChart, type BarDatum } from "@/components/shared/bar-chart";
import { BentoCard } from "@/components/shared/bento-card";
import { DonutChart } from "@/components/shared/charts";
import { DataUnavailable } from "@/components/shared/data-unavailable";
import { EmptyState } from "@/components/shared/empty-state";
import { MetricCard } from "@/components/shared/metric-card";
import { PageHeader } from "@/components/shared/page-header";
import { Icon } from "@/components/ui/icon";
import { getPayrollRuns, getRunPayslips } from "@/lib/api/payroll";
import { formatDateRange, formatMoney, formatMoneyCompact } from "@/lib/format";
import { monthLabel, statutoryTotals } from "@/lib/payroll-stats";

/**
 * Payroll reports. Figures come from the selected run's payslips; the one report the
 * backend generates for payroll is the Payroll Register PDF, which also lists the
 * statutory totals to remit. Separate PAYE / NSSF / SHIF / Housing Levy return files
 * and bank advice are not generated by the system.
 */
export default async function PayrollReportsPage({
  searchParams,
}: {
  searchParams: Promise<{ run?: string }>;
}) {
  await requirePermission("report:read");
  const { run: runParam } = await searchParams;

  let runs: Awaited<ReturnType<typeof getPayrollRuns>>;
  try {
    runs = await getPayrollRuns();
  } catch (error) {
    return (
      <DataUnavailable
        title="Payroll Reports"
        subject="The payroll run list"
        reason={error instanceof Error ? error.message : undefined}
      />
    );
  }

  if (runs.length === 0) {
    return (
      <>
        <PageHeader title="Payroll Reports" />
        <EmptyState symbol="analytics" title="No reports yet" description="Reports are available once payroll has been run." />
      </>
    );
  }

  const requested = Number(runParam);
  const selected = runs.find((run) => run.id === requested) ?? runs[0];

  let payslips: Awaited<ReturnType<typeof getRunPayslips>>;
  try {
    payslips = await getRunPayslips(selected.id);
  } catch (error) {
    return (
      <DataUnavailable
        title="Payroll Reports"
        subject="The payslips for this run"
        reason={error instanceof Error ? error.message : undefined}
      />
    );
  }

  const statutory = statutoryTotals(payslips);
  const gross = selected.totalGrossPayroll ?? 0;
  const avgCost = selected.payslipCount > 0 ? gross / selected.payslipCount : 0;

  const trend: BarDatum[] = runs
    .slice(0, 6)
    .reverse()
    .map((run) => ({
      label: monthLabel(run.periodEnd),
      value: run.totalGrossPayroll ?? 0,
      tooltip: formatMoney(run.totalGrossPayroll),
    }));
  const trendMax = Math.max(1, ...trend.map((point) => point.value));

  const pct = (value: number) => (statutory.total > 0 ? Math.round((value / statutory.total) * 100) : 0);
  const split = [
    { label: "PAYE", value: pct(statutory.paye), color: "var(--color-primary)" },
    { label: "NSSF", value: pct(statutory.nssf), color: "var(--color-amber-main)" },
    { label: "SHIF", value: pct(statutory.shif), color: "var(--color-green-main)" },
    { label: "Housing Levy", value: pct(statutory.housingLevy), color: "var(--color-error)" },
  ];

  return (
    <>
      <PageHeader
        title="Payroll Reports"
        description={`Run #${selected.id} · ${formatDateRange(selected.periodStart, selected.periodEnd)}`}
        actions={
          <form method="get" className="flex items-center gap-2">
            <select
              name="run"
              defaultValue={selected.id}
              className="rounded-lg border border-outline-variant bg-surface-container-lowest px-3 py-2 text-sm text-on-surface focus:outline-none focus:ring-1 focus:ring-primary"
            >
              {runs.map((run) => (
                <option key={run.id} value={run.id}>
                  {formatDateRange(run.periodStart, run.periodEnd)} · Run #{run.id}
                </option>
              ))}
            </select>
            <button type="submit" className="rounded-lg bg-secondary-container px-4 py-2 text-sm font-medium text-on-secondary-container hover:bg-primary-fixed">
              View
            </button>
          </form>
        }
      />

      <div className="grid grid-cols-1 gap-gutter md:grid-cols-4">
        <MetricCard label="Total Gross" value={formatMoneyCompact(selected.totalGrossPayroll)} icon="account_balance_wallet" tone="primary" />
        <MetricCard label="Total Net" value={formatMoneyCompact(selected.totalNetPayroll)} icon="payments" tone="primary" />
        <MetricCard label="Statutory To Remit" value={formatMoneyCompact(statutory.total)} icon="gavel" tone="error" hint="PAYE, NSSF, SHIF, Housing Levy" />
        <MetricCard label="Avg Cost / Employee" value={formatMoneyCompact(avgCost)} icon="person" hint={`${selected.payslipCount} employees`} />
      </div>

      <div className="mt-gutter grid grid-cols-1 gap-gutter md:grid-cols-2">
        <BentoCard title="Cost Trend (6 Runs)" subtitle="Gross payroll" className="flex min-h-[300px] flex-col" bodyClassName="flex flex-1 flex-col rounded-lg bg-surface-container-low/50 p-2">
          <BarChart
            data={trend}
            max={trendMax}
            axisLabels={[formatMoneyCompact(trendMax, { showCurrency: false }), formatMoneyCompact(trendMax / 2, { showCurrency: false }), "0"]}
            tone="primary"
          />
        </BentoCard>
        <BentoCard title="Statutory Split" subtitle="Share of amounts to remit (%)" className="flex min-h-[300px] flex-col" bodyClassName="flex flex-1 flex-col justify-center">
          {statutory.total > 0 ? (
            <DonutChart segments={split} size={160} legend="value" centerLabel="Share %" />
          ) : (
            <EmptyState symbol="donut_large" title="No statutory data" />
          )}
        </BentoCard>
      </div>

      <h3 className="mb-4 mt-gutter text-lg font-bold text-on-surface">Reports for this run</h3>
      <div className="grid grid-cols-1 gap-gutter md:grid-cols-3">
        <div className="group relative flex flex-col gap-3 rounded-card border border-transparent bg-surface-container-lowest p-5 shadow-ambient-1 transition-colors hover:border-primary-fixed-dim hover:shadow-ambient-2">
          <div className="flex items-start gap-3">
            <span className="rounded-lg bg-surface-container-high p-2 text-on-surface transition-colors group-hover:bg-primary-container group-hover:text-on-primary-container">
              <Icon name="list_alt" />
            </span>
            <div className="flex-1">
              <h4 className="text-sm font-bold text-on-surface">Payroll Register</h4>
              <p className="mt-1 text-xs text-on-surface-variant">
                Every employee&apos;s gross, deductions and net, plus the statutory totals to remit and the employer NITA levy.
              </p>
            </div>
          </div>
          <div className="mt-auto flex justify-end border-t border-surface-variant pt-3">
            <a
              href={`/api/reports/payroll-register?runId=${selected.id}`}
              target="_blank"
              rel="noopener noreferrer"
              className="flex items-center gap-1 rounded px-3 py-1.5 text-xs font-bold text-primary transition-colors hover:bg-surface-container-low"
            >
              Open PDF
              <Icon name="arrow_forward" className="text-[14px]" />
            </a>
          </div>
        </div>
      </div>
    </>
  );
}